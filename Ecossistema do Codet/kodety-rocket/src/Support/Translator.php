    }

    public static function normalize(?string $locale): string
    {
        $locale = str_replace('-', '_', (string) $locale);

        $aliases = [
            'en' => 'en_US',
            'en_US' => 'en_US',
            'pt' => 'pt_BR',
            'pt_BR' => 'pt_BR',
            'es' => 'es_ES',
            'es_ES' => 'es_ES',
        ];

        return $aliases[$locale] ?? self::DEFAULT_LOCALE;
    }

    public static function get(string $key, ?string $locale = null): string
    {
        $locale = self::normalize($locale);

        return self::CATALOGUES[$locale][$key]
            ?? self::CATALOGUES[self::DEFAULT_LOCALE][$key]
            ?? $key;
    }

    /** @return array<string, array<string, string>> */
    public static function catalogues(): array
    {
        return self::CATALOGUES;
    }
