function interpolate(template: string, replacements: Replacements = {}): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(replacements, key) ? String(replacements[key]) : match
  ));
}

export function studioText(language: StudioLanguage, source: string, replacements?: Replacements): string {
  return interpolate(language === 'en' ? (english[source] || source) : source, replacements);
}

type StudioI18n = {
  language: StudioLanguage;
  t(source: string, replacements?: Replacements): string;
};

const StudioI18nContext = createContext<StudioI18n>({
  language: 'pt',
  t: source => source,
});

export function StudioI18nProvider({
  language,
  children,
}: {
  language: StudioLanguage;
  children: ReactNode;
}) {
  const value = useMemo<StudioI18n>(() => ({
    language,
    t: (source, replacements) => studioText(language, source, replacements),
  }), [language]);
  return <StudioI18nContext.Provider value={value}>{children}</StudioI18nContext.Provider>;
}

export function useStudioI18n(): StudioI18n {
  return useContext(StudioI18nContext);
}
