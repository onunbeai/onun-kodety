import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const server = await createServer({ root, configFile: false, logLevel: 'silent', server: { middlewareMode: true, hmr: false }, resolve: { alias: { '@': root } } });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const module = await server.ssrLoadModule('/lib/html-editor/interactions.ts');
  const vendor = await readFile(path.join(root, 'node_modules/motion/dist/motion.js'), 'utf8');
  const adapter = (await readFile(path.join(root, 'lib/html-editor/motion-runtime.js'), 'utf8')).replace(/^export /gm, '');
  await page.setContent('<style>body{margin:0}.box{width:100px;height:100px;background:rgb(255,0,0)}</style><div id="box" class="box"></div><div id="second" class="box"></div>');
  await page.addScriptTag({ content: vendor });
  await page.addScriptTag({ content: adapter + '\nwindow.engine=createOnunMotionRuntime(window.Motion,window);' });
  const results = await page.evaluate(async () => {
    const engine = window.engine, box = document.querySelector('#box'), second = document.querySelector('#second');
    const value = () => ({ x: new DOMMatrix(getComputedStyle(box).transform).m41, opacity: Number(getComputedStyle(box).opacity) });
    engine.set(box, { x: 0, opacity: 0 });
    const timeline = engine.timeline({ paused: true });
    timeline.fromTo(box, { x: 0, opacity: 0 }, { x: 100, opacity: 1, duration: 1, ease: 'none' }, 0);
    timeline.to(box, { x: 200, duration: 1, ease: 'none' }, 1);
    timeline.totalTime(.5); const half = value();
    timeline.totalTime(1.5); const later = value();
    timeline.totalTime(.25); const rewind = value();
    let forwards = 0, backwards = 0;
    timeline.call(() => { if (timeline.time() < .5) backwards++; else forwards++; }, undefined, .4);
    timeline.totalTime(.8); timeline.totalTime(.2); const callbacks = [forwards, backwards];
    const repeated = engine.timeline({ paused: true, repeat: 1, yoyo: true });
    repeated.fromTo(second, { x: 0 }, { x: 100, duration: 1, ease: 'none' }, 0);
    repeated.totalTime(1.25); const yoyo = new DOMMatrix(getComputedStyle(second).transform).m41;
    const actionRepeat = engine.timeline({ paused: true });
    actionRepeat.fromTo(second, { x: 0 }, { x: 100, duration: 1, repeat: 1, repeatDelay: .25, yoyo: true, ease: 'none' }, 0);
    actionRepeat.totalTime(1.75); const actionYoyo = new DOMMatrix(getComputedStyle(second).transform).m41;
    const stagger = engine.timeline({ paused: true });
    stagger.fromTo([box, second], { opacity: 0 }, { opacity: 1, duration: 1, stagger: .5, ease: 'none' }, 0);
    stagger.totalTime(.75); const staggered = [Number(getComputedStyle(box).opacity), Number(getComputedStyle(second).opacity)];
    engine.easing.create('curve', '.42,0,.58,1');
    const smooth = engine.timeline({ paused: true }).fromTo(box, { x: 0 }, { x: 100, duration: 1, ease: 'curve' }, 0);
    smooth.totalTime(.5); const custom = value().x;
    const object = { x: 0 }; let updates = 0;
    const live = engine.to(object, { x: 10, duration: .08, ease: 'none', onUpdate: () => updates++ });
    await new Promise(resolve => setTimeout(resolve, 160));
    const played = object.x; live.reverse(); await new Promise(resolve => setTimeout(resolve, 150));
    const reversed = object.x;
    const driven = engine.timeline({ paused: true }).fromTo(box, { x: 0 }, { x: 200, duration: 1, ease: 'none' }, 0);
    engine.to(driven, { progress: .75, duration: .05, ease: 'none' }); await new Promise(resolve => setTimeout(resolve, 120));
    const pointer = value().x;
    let clipComplete = 0, delayComplete = 0;
    const callbackTimeline = engine.timeline({ paused: true });
    callbackTimeline.to(object, { x: 20, duration: .1, onComplete: () => clipComplete++ }, 0);
    callbackTimeline.to(object, { duration: .2, onComplete: () => delayComplete++ }, .1);
    callbackTimeline.totalTime(.3); callbackTimeline.totalTime(.3);
    const callbackDuration = callbackTimeline.duration();
    const once = engine.to(object, { x: 0, duration: .1, repeat: 2, yoyo: true, paused: true });
    const repeatDuration = once.totalDuration(); once.totalTime(.25);
    const actionCycleValue = object.x;
    const amount = engine.timeline({ paused: true }).fromTo([box, second], { opacity: 0 }, { opacity: 1, duration: 1, stagger: { amount: 1 }, ease: 'none' }, 0);
    amount.totalTime(1); const amountValues = [Number(getComputedStyle(box).opacity), Number(getComputedStyle(second).opacity)];
    const degrees = engine.timeline({ paused: true }).fromTo(box, { rotation: '0deg' }, { rotation: '90deg', duration: 1, ease: 'none' }, 0);
    degrees.totalTime(.5); const rotation = Math.atan2(new DOMMatrix(getComputedStyle(box).transform).b, new DOMMatrix(getComputedStyle(box).transform).a) * 180 / Math.PI;
    const cleanup = document.createElement('div'); cleanup.setAttribute('style', 'color: blue; padding: 7px;'); document.body.appendChild(cleanup);
    const originalStyle = cleanup.getAttribute('style'); engine.set(cleanup, { x: 40, opacity: .2 }); engine.set(cleanup, { clearProps: 'all' });
    const restoredStyle = cleanup.getAttribute('style'); cleanup.remove();
    const infinite = engine.to(object, { x: 10, duration: 1, repeat: -1, yoyo: true, ease: 'none', paused: true });
    infinite.totalTime(2.5); const infiniteValue = object.x; const infiniteDuration = infinite.totalDuration();
    let loopEvents = 0;
    const loopCalls = engine.timeline({ paused: true, repeat: 1 }).to({ value: 0 }, { value: 1, duration: 1 }, 0).call(() => loopEvents++, undefined, .4);
    loopCalls.totalTime(.6); loopCalls.totalTime(1.6); loopCalls.kill();
    callbackTimeline.kill(); once.kill(); amount.kill(); degrees.kill(); infinite.kill();
    live.kill(); timeline.kill(); repeated.kill(); actionRepeat.kill(); stagger.kill(); smooth.kill(); driven.kill();
    return { half, later, rewind, callbacks, yoyo, actionYoyo, staggered, custom, played, reversed, updates, pointer, clipComplete, delayComplete, callbackDuration, repeatDuration, actionCycleValue, amountValues, rotation, originalStyle, restoredStyle, infiniteValue, infiniteDuration, loopEvents };
  });
  assert.ok(Math.abs(results.half.x - 50) < .1 && Math.abs(results.half.opacity - .5) < .01);
  assert.ok(Math.abs(results.later.x - 150) < .1, 'Consecutive keyframes must start from the preceding segment.');
  assert.ok(Math.abs(results.rewind.x - 25) < .1, 'Seeking backwards must restore the authored segment.');
  assert.deepEqual(results.callbacks, [1, 1], 'Callbacks must cross their boundary in both directions.');
  assert.ok(Math.abs(results.yoyo - 75) < .1 && Math.abs(results.actionYoyo - 50) < .1);
  assert.deepEqual(results.staggered, [.75, .25]);
  assert.ok(Math.abs(results.custom - 50) < .1);
  assert.ok(results.played > 9.9 && results.reversed < .1 && results.updates > 1, 'Playback and reverse must use the real Motion frame clock.');
  assert.ok(Math.abs(results.pointer - 150) < .1, 'Pointer smoothing must animate timeline progress.');
  assert.equal(results.loopEvents, 2, 'Seeking across a repeat boundary must run each crossed callback.');
  assert.equal(results.clipComplete, 1); assert.equal(results.delayComplete, 1);
  assert.ok(Math.abs(results.callbackDuration - .3) < .0001, 'Callback-only clips must contribute duration.');
  assert.ok(Math.abs(results.repeatDuration - .3) < .0001, 'Standalone repeat must be applied once, not at both clip and timeline levels.');
  assert.deepEqual(results.amountValues, [1, 0], 'Stagger amount must distribute over the whole target collection.');
  assert.ok(Math.abs(results.rotation - 45) < .01, 'Degree strings must interpolate as angles.');
  assert.equal(results.restoredStyle, results.originalStyle, 'clearProps all must preserve authored inline styles.');
  assert.equal(results.infiniteDuration, Infinity); assert.ok(Number.isFinite(results.infiniteValue), 'Infinite repeat must remain numerically seekable.');


  const action = { ...module.createInteractionAction('animate', { selector: '#target', mode: 'selector', scope: 'document' }), from: { x: 0, opacity: 0 }, to: { x: 120, opacity: 1 }, duration: .12, ease: 'none' };
  const make = (trigger, options = {}) => ({ ...module.DEFAULT_INTERACTION, id: 'motion-test', name: 'Motion test', trigger, triggerSelector: '#target', triggerLabel: 'Target', triggerTargetMode: 'selector', actions: [action], ...options });
  const html = interaction => module.patchInteractionDocument('<!doctype html><html><head><script>window.Motion={authored:true};window.gsap={authored:true};</script><style>body{margin:0;min-height:3000px}#target{width:100px;height:100px;background:red}</style></head><body><div id="target">Hello Motion</div></body></html>', { version: 2, interactions: [interaction] });
  assert.match(html(make('click')), /Permission is hereby granted, free of charge/, 'Standalone HTML must retain Motion’s MIT notice.');
  await page.setContent(html(make('click')), { waitUntil: 'load' });
  await page.waitForFunction(() => window.__kodetyInteractions?.get('motion-test'));
  assert.deepEqual(await page.evaluate(() => [window.Motion.authored, window.gsap.authored, window.__ONUN_MOTION_ENGINE__.engine]), [true, true, 'Motion']);
  await page.locator('#target').click({ force: true });
  await page.waitForTimeout(240);
  assert.ok(await page.locator('#target').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41 > 119), 'Published click interaction must run using the inlined Motion dependency.');
  await page.locator('#target').click({ force: true });
  await page.waitForTimeout(230);
  assert.ok(await page.locator('#target').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41 < 1), 'Click-toggle must reverse.');
  await page.setContent(html(make('scroll', { scrollStart: 'top top', scrollEnd: '+=800', scrollScrub: true, scrollSmoothing: 0 })), { waitUntil: 'load' });
  await page.waitForFunction(() => window.__kodetyInteractions?.get('motion-test'));
  await page.evaluate(() => scrollTo(0, 400)); await page.waitForTimeout(120);
  assert.ok(await page.locator('#target').evaluate(element => Math.abs(new DOMMatrix(getComputedStyle(element).transform).m41 - 60) < 2), 'Exported scroll interaction must scrub at the configured range.');
  await page.evaluate(() => scrollTo(0, 0));
  await page.setContent(html(make('hover')), { waitUntil: 'load' });
  await page.waitForFunction(() => window.__kodetyInteractions?.get('motion-test'));
  await page.locator('#target').dispatchEvent('mouseenter'); await page.waitForTimeout(230);
  assert.ok(await page.locator('#target').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41 > 119));
  await page.locator('#target').dispatchEvent('mouseleave'); await page.waitForTimeout(230);
  assert.ok(await page.locator('#target').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41 < 1));
  await page.setContent(html(make('mouse-move', { mouseMoveAxis: 'x', mouseMoveSmoothing: .05 })), { waitUntil: 'load' });
  await page.waitForFunction(() => window.__kodetyInteractions?.get('motion-test'));
  await page.locator('#target').dispatchEvent('mousemove', { clientX: 50, clientY: 50 }); await page.waitForTimeout(170);
  assert.ok(await page.locator('#target').evaluate(element => Math.abs(new DOMMatrix(getComputedStyle(element).transform).m41 - 60) < 2));
  await page.locator('#target').dispatchEvent('mouseleave'); await page.waitForTimeout(170);
  assert.ok(await page.locator('#target').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41 < 1));
  const textInteraction = make('click', { actions: [{ ...action, textSplit: 'chars', stagger: .01 }] });
  const frozen = html(textInteraction).replace('<head>', '<head><script>window.__KODETY_EDITOR_MOTION_FROZEN__=true;</script>');
  await page.setContent(frozen, { waitUntil: 'load' });
  await page.waitForFunction(() => window.__kodetyInteractions?.get('motion-test'));
  assert.equal(await page.locator('#target > span').count(), 0, 'Frozen canvas must not split text before an explicit preview.');
  await page.evaluate(() => window.__kodetyInteractions.get('motion-test').seek(.06));
  assert.ok(await page.locator('#target > span').count() > 5);
  assert.ok(await page.locator('#target > span').first().evaluate(element => Math.abs(new DOMMatrix(getComputedStyle(element).transform).m41 - 60) < 1));
  await page.evaluate(() => window.__kodetyInteractions.get('motion-test').release());
  assert.equal(await page.locator('#target > span').count(), 0);
  assert.equal(await page.locator('#target').textContent(), 'Hello Motion');
  await page.evaluate(() => { delete window.__KODETY_EDITOR_MOTION_FROZEN__; });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setContent(html(make('click')), { waitUntil: 'load' });
  await page.waitForFunction(() => window.__kodetyInteractions?.get('motion-test'));
  assert.ok(await page.locator('#target').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41 > 119), 'Reduced motion must settle the visual track without playing it.');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  assert.deepEqual(errors, []);
  console.log('Motion browser runtime: real playback, reverse, keyframes, seek, callbacks, repeat/yoyo, stagger, custom easing, object/pointer, exported click/hover/pointer/scroll, frozen text preview/release, reduced motion and global isolation passed.');
} finally { await page.close(); await browser.close(); await server.close(); }
